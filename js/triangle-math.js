/* Triangle solver — pure math, no DOM.
 * Sides a, b, c are opposite angles A, B, C. Angles in degrees.
 * Works as a plain browser script (window.TriangleMath) and under node. */
(function (root) {
  'use strict';

  var SIDES = ['a', 'b', 'c'];
  var ANGLES = ['A', 'B', 'C'];
  var FIELDS = SIDES.concat(ANGLES);
  var DECIMALS = 3;
  var RAD = Math.PI / 180;

  function clamp1(x) { return Math.max(-1, Math.min(1, x)); }
  function sin(d) { return Math.sin(d * RAD); }
  function cos(d) { return Math.cos(d * RAD); }
  function asinD(x) { return Math.asin(clamp1(x)) / RAD; }
  function acosD(x) { return Math.acos(clamp1(x)) / RAD; }

  function isAngle(f) { return ANGLES.indexOf(f) >= 0; }
  function others(i) { return [0, 1, 2].filter(function (n) { return n !== i; }); }

  function fmt(n) {
    if (!isFinite(n)) return '—';
    var s = n.toFixed(DECIMALS);
    if (s.indexOf('.') >= 0) s = s.replace(/0+$/, '').replace(/\.$/, '');
    return s === '-0' ? '0' : s;
  }

  function fmtField(f, n) { return isAngle(f) ? fmt(n) + '°' : fmt(n); }

  // Accepts "12", "12.5", ".5", "12,5". Anything else is NaN.
  function parseNum(text) {
    var s = String(text == null ? '' : text).trim().replace(',', '.');
    if (!/^[-+]?(\d+\.?\d*|\.\d+)$/.test(s)) return NaN;
    return parseFloat(s);
  }

  // order: typed fields, most recent first. Returns the fields to solve from:
  // the 3 most recent, skipping a 3rd angle (it adds nothing without a side).
  function pickInputs(order) {
    var picked = [], angles = 0;
    for (var i = 0; i < order.length && picked.length < 3; i++) {
      var f = order[i];
      if (FIELDS.indexOf(f) < 0 || picked.indexOf(f) >= 0) continue;
      if (isAngle(f)) {
        if (angles === 2) continue;
        angles++;
      }
      picked.push(f);
    }
    return picked;
  }

  // --- solution building -------------------------------------------------

  function newSolution() { return { v: {}, work: {} }; }

  // Record a solved value and its work. The substituted line is generated by
  // replacing field letters on the right of '=' with their current values.
  function put(sol, f, value, formula) {
    sol.v[f] = value;
    var eq = formula.indexOf('=');
    var lhs = formula.slice(0, eq).trim();
    var rhs = formula.slice(eq + 1).replace(/\b[abcABC]\b/g, function (k) {
      return fmtField(k, sol.v[k]);
    });
    sol.work[f] = {
      formula: formula,
      sub: lhs + ' =' + rhs,
      result: lhs + ' = ' + (f === 'area' || f === 'perimeter' ? fmt(value) : fmtField(f, value))
    };
  }

  function thirdAngle(sol, i) {
    var o = others(i), J = ANGLES[o[0]], K = ANGLES[o[1]];
    put(sol, ANGLES[i], 180 - sol.v[J] - sol.v[K], ANGLES[i] + ' = 180° − ' + J + ' − ' + K);
  }

  // Side i from known side k and angles i, k.
  function sideBySines(sol, i, k) {
    var Si = SIDES[i], Sk = SIDES[k], Gi = ANGLES[i], Gk = ANGLES[k];
    put(sol, Si, sol.v[Sk] * sin(sol.v[Gi]) / sin(sol.v[Gk]),
      Si + ' = ' + Sk + '·sin ' + Gi + ' / sin ' + Gk);
  }

  // Angle i from all three sides.
  function angleByCosines(sol, i) {
    var o = others(i), Si = SIDES[i], Sj = SIDES[o[0]], Sk = SIDES[o[1]];
    var v = sol.v;
    put(sol, ANGLES[i], acosD((v[Sj] * v[Sj] + v[Sk] * v[Sk] - v[Si] * v[Si]) / (2 * v[Sj] * v[Sk])),
      ANGLES[i] + ' = acos((' + Sj + '² + ' + Sk + '² − ' + Si + '²) / (2·' + Sj + '·' + Sk + '))');
  }

  function addExtras(sol) {
    var v = sol.v;
    put(sol, 'area', 0.5 * v.b * v.c * sin(v.A), 'Area = ½·b·c·sin A');
    put(sol, 'perimeter', v.a + v.b + v.c, 'P = a + b + c');
  }

  function seed(given) {
    var sol = newSolution();
    Object.keys(given).forEach(function (f) { sol.v[f] = given[f]; });
    return sol;
  }

  function solveSSS(given) {
    var s = [given.a, given.b, given.c];
    for (var i = 0; i < 3; i++) {
      var o = others(i);
      if (s[i] >= (s[o[0]] + s[o[1]]) * (1 - 1e-12)) {
        return { error: 'No triangle: ' + SIDES[i] + ' ≥ ' + SIDES[o[0]] + ' + ' + SIDES[o[1]] };
      }
    }
    var sol = seed(given);
    angleByCosines(sol, 0);
    angleByCosines(sol, 1);
    thirdAngle(sol, 2);
    return { solutions: [sol] };
  }

  // Two sides j, k and the angle i between them.
  function solveSAS(given, i) {
    var o = others(i), Si = SIDES[i], Sj = SIDES[o[0]], Sk = SIDES[o[1]], Gi = ANGLES[i];
    var sol = seed(given), v = sol.v;
    put(sol, Si, Math.sqrt(v[Sj] * v[Sj] + v[Sk] * v[Sk] - 2 * v[Sj] * v[Sk] * cos(v[Gi])),
      Si + ' = √(' + Sj + '² + ' + Sk + '² − 2·' + Sj + '·' + Sk + '·cos ' + Gi + ')');
    angleByCosines(sol, o[0]);
    thirdAngle(sol, o[1]);
    return { solutions: [sol] };
  }

  // Angle x with its opposite side x, plus side y. May have 0, 1 or 2 answers.
  function solveSSA(given, x, y) {
    var z = 3 - x - y;
    var Sx = SIDES[x], Sy = SIDES[y], Gx = ANGLES[x], Gy = ANGLES[y];
    var r = given[Sy] * sin(given[Gx]) / given[Sx];
    if (r > 1 + 1e-12) {
      return { error: 'No triangle: ' + Sy + '·sin ' + Gx + ' > ' + Sx };
    }
    // r ≈ 1: side x just touches — a single right angle at y.
    var tangent = r >= 1 - 1e-10;
    var y1 = tangent ? 90 : asinD(r);
    var candidates = [
      { angle: y1, formula: Gy + ' = asin(' + Sy + '·sin ' + Gx + ' / ' + Sx + ')' },
      { angle: 180 - y1, formula: Gy + ' = 180° − asin(' + Sy + '·sin ' + Gx + ' / ' + Sx + ')' }
    ];
    if (tangent) candidates.pop();
    var solutions = candidates.filter(function (cand) {
      return given[Gx] + cand.angle < 180 - 1e-9;
    }).map(function (cand) {
      var sol = seed(given);
      put(sol, Gy, cand.angle, cand.formula);
      thirdAngle(sol, z);
      sideBySines(sol, z, x);
      return sol;
    });
    if (!solutions.length) return { error: 'No triangle: ' + Sx + ' too short for ' + Gx };
    return { solutions: solutions };
  }

  // Two angles and one side.
  function solveAngles(given, angleIdx, sideIdx) {
    var sum = given[ANGLES[angleIdx[0]]] + given[ANGLES[angleIdx[1]]];
    if (sum >= 180 - 1e-9) {
      return { error: 'No triangle: ' + ANGLES[angleIdx[0]] + ' + ' + ANGLES[angleIdx[1]] + ' ≥ 180°' };
    }
    var missing = 3 - angleIdx[0] - angleIdx[1];
    var sol = seed(given);
    thirdAngle(sol, missing);
    others(sideIdx).forEach(function (i) { sideBySines(sol, i, sideIdx); });
    return { solutions: [sol] };
  }

  function needMessage(sides, angles) {
    var n = 3 - sides - angles;
    if (sides === 0 && angles === 2) return 'Enter a side';
    var msg = 'Enter ' + n + ' more value' + (n === 1 ? '' : 's');
    return sides === 0 ? msg + ' (at least 1 side)' : msg;
  }

  // given: { field: number } with exactly the picked inputs.
  // Returns { case, solutions: [{ v, work }] } or { error, incomplete? }.
  function solve(given) {
    var names = Object.keys(given).filter(function (f) { return FIELDS.indexOf(f) >= 0; });
    for (var n = 0; n < names.length; n++) {
      var f = names[n], val = given[f];
      if (!isFinite(val)) return { error: f + ' is not a number' };
      if (isAngle(f) && (val <= 0 || val >= 180)) return { error: f + ' must be between 0° and 180°' };
      if (!isAngle(f) && val <= 0) return { error: f + ' must be > 0' };
    }
    var sideIdx = SIDES.map(function (s, i) { return names.indexOf(s) >= 0 ? i : -1; })
      .filter(function (i) { return i >= 0; });
    var angleIdx = ANGLES.map(function (g, i) { return names.indexOf(g) >= 0 ? i : -1; })
      .filter(function (i) { return i >= 0; });

    if (names.length < 3) {
      return { incomplete: true, error: needMessage(sideIdx.length, angleIdx.length) };
    }
    if (sideIdx.length === 0) return { error: 'Need at least 1 side' };

    var result, kase;
    if (sideIdx.length === 3) {
      kase = 'SSS';
      result = solveSSS(given);
    } else if (sideIdx.length === 2) {
      var g = angleIdx[0];
      if (sideIdx.indexOf(g) < 0) {
        kase = 'SAS';
        result = solveSAS(given, g);
      } else {
        kase = 'SSA';
        result = solveSSA(given, g, sideIdx[0] === g ? sideIdx[1] : sideIdx[0]);
      }
    } else {
      // Side between the two known angles → ASA, otherwise AAS.
      kase = angleIdx.indexOf(sideIdx[0]) < 0 ? 'ASA' : 'AAS';
      result = solveAngles(given, angleIdx, sideIdx[0]);
    }
    result.case = kase;
    if (result.solutions) result.solutions.forEach(addExtras);
    return result;
  }

  // Angles for drawing a schematic: none below min, right angles kept at 90,
  // obtuse stays obtuse. Degrees taken first from acute angles, then obtuse.
  // Returns the input unchanged when every angle is already >= min.
  function diagramAngles(g, min) {
    if (Math.min.apply(null, g) >= min) return g.slice();
    var d = g.map(function (x) { return Math.max(x, min); });
    var deficit = d[0] + d[1] + d[2] - 180;
    var right = g.map(function (x) { return Math.abs(x - 90) < 1e-6; });
    [function (x) { return x < 90; }, function (x) { return x > 90; }].forEach(function (pool) {
      var idx = [0, 1, 2].filter(function (i) { return g[i] > min && !right[i] && pool(g[i]); });
      // Obtuse angles only give down to just above 90; acute down to min.
      var floor = function (i) { return g[i] > 90 ? 90 + 1 : min; };
      var room = idx.reduce(function (sum, i) { return sum + d[i] - floor(i); }, 0);
      if (deficit <= 0 || room <= 0) return;
      var take = Math.min(deficit, room);
      idx.forEach(function (i) { d[i] -= take * (d[i] - floor(i)) / room; });
      deficit -= take;
    });
    return d;
  }

  var api = {
    SIDES: SIDES,
    ANGLES: ANGLES,
    FIELDS: FIELDS,
    isAngle: isAngle,
    fmt: fmt,
    fmtField: fmtField,
    parseNum: parseNum,
    pickInputs: pickInputs,
    solve: solve,
    diagramAngles: diagramAngles
  };

  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.TriangleMath = api;
})(this);
